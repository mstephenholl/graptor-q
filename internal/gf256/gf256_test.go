// forEachTier runs f once with every supported kernel tier active.
func forEachTier(t *testing.T, f func(t *testing.T)) {
	for _, name := range Tiers() {
		t.Run(name, func(t *testing.T) {
			defer Use(name)()
			f(t)
		})
	}
}

func refMulAdd(dst, src []byte, c byte) {
	for i := range src {
		dst[i] ^= Mul(c, src[i])
	}
}

var testLengths = func() []int {
	var n []int
	for i := 0; i <= 260; i++ {
		n = append(n, i)
	}
	return append(n, 511, 512, 513, 1023, 1280, 4096+13, 65536+7)
}()

func TestKernels(t *testing.T) {
	forEachTier(t, func(t *testing.T) {
		rng := rand.New(rand.NewPCG(1, 2))
		buf := make([]byte, 3*(65536+64))
		for _, n := range testLengths {
			for _, c := range []byte{0, 1, 2, 3, 0x1d, 0x80, 0xfe, 0xff, byte(rng.IntN(256))} {
				off := rng.IntN(32)
				for i := range buf {
					buf[i] = byte(rng.Uint32())
				}
				src := buf[off : off+n]
				dst := buf[len(buf)/2+off/2 : len(buf)/2+off/2+n]
				orig := bytes.Clone(dst)

				want := bytes.Clone(orig)
				refMulAdd(want, src, c)
				MulAddSlice(dst, src, c)
				if !bytes.Equal(dst, want) {
					t.Fatalf("MulAddSlice n=%d c=%d off=%d mismatch", n, c, off)
				}

				copy(dst, orig)
				want = make([]byte, n)
				refMulAdd(want, src, c)
				MulSlice(dst, src, c)
				if !bytes.Equal(dst, want) {
					t.Fatalf("MulSlice n=%d c=%d off=%d mismatch", n, c, off)
				}

				copy(dst, orig)
				want = bytes.Clone(orig)
				refMulAdd(want, src, 1)
				AddSlice(dst, src)
				if !bytes.Equal(dst, want) {
					t.Fatalf("AddSlice n=%d off=%d mismatch", n, off)
				}

				// In place: dst = c*dst, and dst = c*dst ^ src.
				copy(dst, orig)
				want = make([]byte, n)
				refMulAdd(want, orig, c)
				MulSlice(dst, dst, c)
				if !bytes.Equal(dst, want) {
					t.Fatalf("in-place MulSlice n=%d c=%d mismatch", n, c)
				}
				copy(dst, orig)
				refMulAdd(want, src, 1)
				ScaleAdd(dst, src, c)
				if !bytes.Equal(dst, want) {
					t.Fatalf("ScaleAdd n=%d c=%d mismatch", n, c)
				}
			}
		}
	})
}

func TestAllConstants(t *testing.T) {
	forEachTier(t, func(t *testing.T) {
		src := make([]byte, 256+77)
		for i := range src {
			src[i] = byte(i)
		}
		for c := range 256 {
			dst := make([]byte, len(src))
			MulSlice(dst, src, byte(c))
			for i, s := range src {
				if dst[i] != Mul(byte(c), s) {
					t.Fatalf("MulSlice c=%d x=%d", c, s)
				}
			}
			MulAddSlice(dst, src, byte(c))
			for i := range dst {
				if dst[i] != 0 {
					t.Fatalf("MulAddSlice c=%d did not cancel at %d", c, i)
				}
			}
		}
	})
}

func TestFusedXor(t *testing.T) {
	forEachTier(t, func(t *testing.T) {
		rng := rand.New(rand.NewPCG(15, 16))
		for _, n := range append(testLengths[:70:70], 95, 96, 97, 127, 128, 129, 1280, 4096+13) {
			for _, k := range []int{0, 1, 2, 3, 7, 8, 9, 16, 17} {
				srcs := make([][]byte, k)
				for i := range srcs {
					srcs[i] = make([]byte, n+rng.IntN(3))[:n] // unaligned capacity
					for j := range srcs[i] {
						srcs[i][j] = byte(rng.Uint32())
					}
				}
				orig := make([]byte, n)
				for j := range orig {
					orig[j] = byte(rng.Uint32())
				}
				want := make([]byte, n)
				for _, s := range srcs {
					refMulAdd(want, s, 1)
				}
				dst := bytes.Clone(orig)
				SetXor(dst, srcs)
				if !bytes.Equal(dst, want) {
					t.Fatalf("SetXor n=%d k=%d mismatch", n, k)
				}
				refMulAdd(want, orig, 1)
				dst = bytes.Clone(orig)
				XorN(dst, srcs)
				if !bytes.Equal(dst, want) {
					t.Fatalf("XorN n=%d k=%d mismatch", n, k)
				}
			}
		}
	})
}

