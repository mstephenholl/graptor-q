func rfcTables(t testing.TB) *rfctext.Tables {
	t.Helper()
	text, err := os.ReadFile("../../testdata/rfc6330.txt")
	if err != nil {
		t.Fatal(err)
	}
	tables, err := rfctext.Parse(text)
	if err != nil {
		t.Fatal(err)
	}
	return tables
}

// The field is built from the polynomial; the RFC defines it by tables. Check
// every product, quotient and inverse against the RFC formulas (Section 5.7.2).
func TestFieldMatchesRFC(t *testing.T) {
	rt := rfcTables(t)
	if rt.OctExp != expTable {
		t.Fatal("OCT_EXP differs from the table generated by polynomial 0x11D")
	}
	for a := 1; a < 256; a++ {
		if rt.OctLog[a] != logTable[a] {
			t.Fatalf("OCT_LOG[%d] = %d, got %d", a, rt.OctLog[a], logTable[a])
		}
	}
	for a := range 256 {
		for b := range 256 {
			want := byte(0)
			if a != 0 && b != 0 {
				want = rt.OctExp[int(rt.OctLog[a])+int(rt.OctLog[b])]
			}
			if got := Mul(byte(a), byte(b)); got != want {
				t.Fatalf("Mul(%d,%d) = %d, want %d", a, b, got, want)
			}
			if b != 0 {
				want = 0
				if a != 0 {
					want = rt.OctExp[int(rt.OctLog[a])-int(rt.OctLog[b])+255]
				}
				if got := Div(byte(a), byte(b)); got != want {
					t.Fatalf("Div(%d,%d) = %d, want %d", a, b, got, want)
				}
			}
		}
		if a != 0 {
			if got, want := Inv(byte(a)), rt.OctExp[255-int(rt.OctLog[a])]; got != want {
				t.Fatalf("Inv(%d) = %d, want %d", a, got, want)
			}
			if Mul(byte(a), Inv(byte(a))) != 1 {
				t.Fatalf("a * Inv(a) != 1 for a=%d", a)
			}
		}
	}
	for i := range 1000 {
		if got, want := Exp(i), rt.OctExp[i%255]; got != want {
			t.Fatalf("Exp(%d) = %d, want %d", i, got, want)
		}
	}
}

func TestDistributive(t *testing.T) {
	for a := range 256 {
		ta := &mulTable[a]
		for b := range 256 {
			for c := range 256 {
				if ta[b^c] != ta[b]^ta[c] {
					t.Fatalf("a*(b+c) != a*b + a*c for %d,%d,%d", a, b, c)
				}
			}
		}
	}
}

// affine emulates GF2P8AFFINEQB for one byte with a zero constant.
func affine(x byte, a uint64) byte {
	var out byte
	for i := range 8 {
		row := byte(a >> (8 * (7 - i)))
		var parity byte
		for v := row & x; v != 0; v &= v - 1 {
			parity ^= 1
		}
		out |= parity << i
	}
	return out
}

